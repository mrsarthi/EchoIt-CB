#!/usr/bin/env node
/**
 * Keep the Android process alive by running a foreground service.
 *
 * ## Why this is needed
 *
 * Android's cached-app freezer takes the whole process — including Rust — at
 * ~90s backgrounded. Measured at zero CPU ticks across three runs (see
 * PROGRESS.md, 2026-08-30). Without a foreground service, nothing app-side can
 * receive messages while the screen is off.
 *
 * ## What the service does
 *
 * 1. Shows a low-priority persistent notification ("EchoIt is connected")
 * 2. Holds a partial wake lock so the CPU stays on
 * 3. Keeps the process in the foreground process group
 *
 * It does NOT start the transport or hold a connection — Rust does that inside
 * the webview. The service is purely a process-keep-alive.
 *
 * ## Message notifications (D2)
 *
 * When a message arrives while backgrounded, the webview tells the service to
 * post a notification with the sender's name. Never the message text (D2):
 * putting message content on a lock screen would undercut the same warning
 * §4.1 gives about an unlocked phone.
 *
 * ## Durability
 *
 * `src-tauri/gen/` is regenerated by `tauri android init`, so this script
 * applies everything fresh each time. Idempotent.
 *
 *   npm run android:foreground   (or npm run android:prepare for all)
 */

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';

const MANIFEST = join(
  'src-tauri', 'gen', 'android', 'app', 'src', 'main', 'AndroidManifest.xml',
);
const ACTIVITY = join(
  'src-tauri', 'gen', 'android', 'app', 'src', 'main', 'java',
  'io', 'github', 'mrsarthi', 'echoit', 'MainActivity.kt',
);
const SERVICE_FILE = join(
  'src-tauri', 'gen', 'android', 'app', 'src', 'main', 'java',
  'io', 'github', 'mrsarthi', 'echoit', 'EchoItService.kt',
);

if (!existsSync(MANIFEST)) {
  console.error(`No ${MANIFEST}. Run \`npx tauri android init\` first.`);
  process.exit(1);
}

// ─── 1. Permissions in AndroidManifest.xml ──────────────────────────────────

let manifest = readFileSync(MANIFEST, 'utf8');

const PERMISSIONS = [
  'android.permission.FOREGROUND_SERVICE',
  'android.permission.FOREGROUND_SERVICE_DATA_SYNC',
  'android.permission.POST_NOTIFICATIONS',
  'android.permission.WAKE_LOCK',
];

for (const perm of PERMISSIONS) {
  if (!manifest.includes(perm)) {
    manifest = manifest.replace(
      '<uses-permission android:name="android.permission.INTERNET" />',
      `<uses-permission android:name="android.permission.INTERNET" />\n    <uses-permission android:name="${perm}" />`,
    );
  }
}

// ─── 2. Service declaration in AndroidManifest.xml ──────────────────────────

/*
 * Rewritten rather than appended-if-absent.
 *
 * The guard used to look for `<service android:name=".EchoItService"` on one
 * line while the block it writes puts the attribute on the next, so it never
 * matched and every run added another copy. A manifest with three identical
 * service declarations was found on a device.
 *
 * Stripping whatever is there and writing one is self-healing, which an
 * `includes` check can never be: it repairs the manifests this script already
 * damaged instead of only declining to damage new ones.
 *
 * `android:stopWithTask="false"` is the reported bug -- swiping EchoIt out of
 * the recents list took the service with it, and with it the whole reason the
 * service exists. `onTaskRemoved` in the service asks to be restarted as well,
 * because the flag alone is not honoured on every OEM build.
 */
const EXISTING_SERVICE = /\s*<service\s+android:name="\.EchoItService"[\s\S]*?\/>\s*/g;
manifest = manifest.replace(EXISTING_SERVICE, `
`);

manifest = manifest.replace(
  '</application>',
  `
        <service
            android:name=".EchoItService"
            android:foregroundServiceType="dataSync"
            android:stopWithTask="false"
            android:exported="false" />

    </application>`,
);

writeFileSync(MANIFEST, manifest, 'utf8');
console.log('android:foreground — permissions and service declaration applied');

// ─── 3. The foreground service itself ───────────────────────────────────────

const SERVICE_KOTLIN = `package io.github.mrsarthi.echoit

import android.app.Notification
import android.app.NotificationChannel
import android.app.NotificationManager
import android.app.PendingIntent
import android.app.Service
import android.content.Context
import android.content.Intent
import android.content.pm.ServiceInfo
import android.os.Build
import android.os.IBinder
import android.os.PowerManager

/**
 * A foreground service that keeps the process alive.
 *
 * Android's cached-app freezer stops the entire process — including Rust —
 * after ~90s backgrounded. A foreground service moves the process out of
 * the freezable group.
 *
 * This does NOT hold a connection or run the transport. Rust inside the
 * webview does that. The service is purely a process keep-alive with a
 * mandatory visible notification.
 */
class EchoItService : Service() {

    companion object {
        private const val CHANNEL_SERVICE = "echoit_service"
        private const val CHANNEL_MESSAGES = "echoit_messages"
        private const val NOTIFICATION_ID = 1
        private const val MSG_NOTIFICATION_BASE = 1000
        private var msgCounter = 0

        fun start(context: Context) {
            val intent = Intent(context, EchoItService::class.java)
            if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.O) {
                context.startForegroundService(intent)
            } else {
                context.startService(intent)
            }
        }

        fun stop(context: Context) {
            context.stopService(Intent(context, EchoItService::class.java))
        }

        /**
         * Post a message notification. Sender name only, never the text (D2).
         *
         * Putting message content on a lock screen would undercut the same
         * warning §4.1 gives about an unlocked phone.
         */
        fun notifyMessage(context: Context, senderName: String) {
            ensureChannels(context)
            val intent = context.packageManager.getLaunchIntentForPackage(context.packageName)
            val pi = PendingIntent.getActivity(
                context, 0, intent,
                PendingIntent.FLAG_UPDATE_CURRENT or PendingIntent.FLAG_IMMUTABLE,
            )
            val notification = Notification.Builder(context, CHANNEL_MESSAGES)
                .setSmallIcon(android.R.drawable.ic_dialog_email)
                .setContentTitle("Message from \$senderName")
                .setContentText("Tap to open")
                .setContentIntent(pi)
                .setAutoCancel(true)
                .build()
            val nm = context.getSystemService(NotificationManager::class.java)
            nm.notify(MSG_NOTIFICATION_BASE + (msgCounter++ % 50), notification)
        }

        private fun ensureChannels(context: Context) {
            if (Build.VERSION.SDK_INT < Build.VERSION_CODES.O) return
            val nm = context.getSystemService(NotificationManager::class.java)
            if (nm.getNotificationChannel(CHANNEL_SERVICE) != null) return

            nm.createNotificationChannel(
                NotificationChannel(
                    CHANNEL_SERVICE,
                    "Connection",
                    NotificationManager.IMPORTANCE_LOW,
                ).apply {
                    description = "Keeps EchoIt connected so messages arrive"
                    setShowBadge(false)
                },
            )
            nm.createNotificationChannel(
                NotificationChannel(
                    CHANNEL_MESSAGES,
                    "Messages",
                    NotificationManager.IMPORTANCE_HIGH,
                ).apply {
                    description = "New message notifications"
                },
            )
        }
    }

    private var wakeLock: PowerManager.WakeLock? = null

    override fun onCreate() {
        super.onCreate()
        ensureChannels(this)

        val intent = packageManager.getLaunchIntentForPackage(packageName)
        val pi = PendingIntent.getActivity(
            this, 0, intent,
            PendingIntent.FLAG_UPDATE_CURRENT or PendingIntent.FLAG_IMMUTABLE,
        )

        val notification = Notification.Builder(this, CHANNEL_SERVICE)
            .setSmallIcon(android.R.drawable.ic_dialog_info)
            .setContentTitle("EchoIt")
            .setContentText("Connected — messages will arrive")
            .setContentIntent(pi)
            .setOngoing(true)
            .build()

        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.UPSIDE_DOWN_CAKE) {
            startForeground(NOTIFICATION_ID, notification, ServiceInfo.FOREGROUND_SERVICE_TYPE_DATA_SYNC)
        } else {
            startForeground(NOTIFICATION_ID, notification)
        }

        // Partial wake lock: keeps the CPU running. Does NOT keep the screen on.
        val pm = getSystemService(PowerManager::class.java)
        wakeLock = pm.newWakeLock(PowerManager.PARTIAL_WAKE_LOCK, "EchoIt::KeepAlive")
        wakeLock?.acquire()
    }

    override fun onDestroy() {
        wakeLock?.release()
        wakeLock = null
        super.onDestroy()
    }

    override fun onBind(intent: Intent?): IBinder? = null

    /**
     * Swiping EchoIt out of the recents list must not stop the service.
     *
     * Reported on a device: closing the app closed the service, which is the
     * one thing it exists not to do -- a messenger that only receives while
     * you are looking at it is the problem, not the feature.
     *
     * android:stopWithTask="false" in the manifest is the declaration; this
     * is the belt to its braces, because several OEM builds stop the service
     * anyway and then honour an explicit restart.
     */
    override fun onTaskRemoved(rootIntent: Intent?) {
        val restart = Intent(applicationContext, EchoItService::class.java)
        startForegroundService(restart)
        super.onTaskRemoved(rootIntent)
    }

    override fun onStartCommand(intent: Intent?, flags: Int, startId: Int): Int {
        return START_STICKY
    }
}
`;

mkdirSync(dirname(SERVICE_FILE), { recursive: true });
writeFileSync(SERVICE_FILE, SERVICE_KOTLIN, 'utf8');
console.log('android:foreground — EchoItService.kt written');

// ─── 4. Wire start/stop into MainActivity.kt ───────────────────────────────

if (!existsSync(ACTIVITY)) {
  console.error(`No ${ACTIVITY}. Run \`npx tauri android init\` first.`);
  process.exit(1);
}

let activity = readFileSync(ACTIVITY, 'utf8');

const SVC_BEGIN = '  // >>> echoit foreground-service (generated by scripts/apply-android-foreground.mjs)';
const SVC_END = '  // <<< echoit foreground-service';

// Strip any previous version (idempotent).
for (;;) {
  const from = activity.indexOf(SVC_BEGIN);
  if (from === -1) break;
  const to = activity.indexOf(SVC_END, from);
  if (to === -1) {
    console.error('Found foreground-service begin marker with no end. Refusing to guess.');
    process.exit(1);
  }
  activity = activity.slice(0, from) + activity.slice(to + SVC_END.length).replace(/^\n/, '');
}

const BACK_NAV_END = '  // <<< echoit back-nav';

if (!activity.includes(BACK_NAV_END)) {
  console.error('The back-nav sentinel is missing. Run android:activity first.');
  process.exit(1);
}

const SVC_BODY = `${SVC_BEGIN}
  /**
   * Start the foreground service so the process stays alive when backgrounded.
   *
   * Also exposes a JavaScript bridge for message notifications (D2): the
   * webview calls EchoItNotify.message(senderName) when a message arrives
   * while backgrounded. Sender name only, never the text.
   */
  override fun onResume() {
    super.onResume()
    EchoItService.start(this)
  }

  private fun wireNotifyBridge(webView: android.webkit.WebView) {
    webView.addJavascriptInterface(
      object {
        @android.webkit.JavascriptInterface
        fun message(senderName: String) {
          EchoItService.notifyMessage(this@MainActivity, senderName)
        }
      },
      "EchoItNotify",
    )
  }
${SVC_END}
`;

// Insert after the back-nav block.
activity = activity.replace(
  BACK_NAV_END,
  BACK_NAV_END + '\n' + SVC_BODY,
);

// Wire the notify bridge into the existing onWebViewCreate.
// The back-nav block has `super.onWebViewCreate(webView)` already.
/*
 * Keep the webview running while backgrounded.
 *
 * Measured 2026-08-31, and this is the half a foreground service does not buy
 * on its own. With the service running the process is no longer frozen -- 302
 * CPU ticks over 180s backgrounded, against **zero** before it -- and yet 0 of
 * 4 messages arrived, with nothing queued on the sender. The bytes left one
 * phone and the other did not act on them.
 *
 * The reason is that EchoIt's protocol runs in the webview, and
 * `TauriActivity` pauses the WebView in `onPause`, which suspends its
 * JavaScript. A live process whose JS is stopped receives nothing.
 *
 * So the pause is undone immediately after the superclass applies it.
 * `resumeTimers()` is process-global rather than per-WebView, which is fine
 * here -- there is one -- and `onResume()` restores this instance's own
 * execution.
 *
 * This is only defensible *because* of the foreground service and its visible
 * notification: keeping JS alive in a backgrounded app that had not told the
 * user it was running would be exactly the battery-draining behaviour the
 * freezer exists to stop.
 */
const KEEP_ALIVE = `
  // >>> echoit keep-alive (generated by scripts/apply-android-foreground.mjs)
  private var echoItWebView: android.webkit.WebView? = null

  override fun onPause() {
    super.onPause()
    // Undo the webview pause TauriActivity applies. Without this the process
    // stays alive and its JavaScript does not, which measured as 0/4 delivered
    // while the CPU was demonstrably running.
    echoItWebView?.let {
      it.onResume()
      it.resumeTimers()
    }
  }
  // <<< echoit keep-alive
`;

if (!activity.includes('echoit keep-alive')) {
  // Before the final closing brace of the class.
  const lastBrace = activity.lastIndexOf('}');
  activity = activity.slice(0, lastBrace) + KEEP_ALIVE + activity.slice(lastBrace);
}

if (!activity.includes('echoItWebView = webView')) {
  activity = activity.replace(
    '    wireNotifyBridge(webView)',
    `    echoItWebView = webView
    wireNotifyBridge(webView)`,
  );
}

// We add wireNotifyBridge(webView) right after the EchoItExit interface.
if (!activity.includes('wireNotifyBridge(webView)')) {
  activity = activity.replace(
    '      "EchoItExit",\n    )\n',
    '      "EchoItExit",\n    )\n\n    wireNotifyBridge(webView)\n',
  );
}

writeFileSync(ACTIVITY, activity, 'utf8');
console.log('android:foreground — service start and notify bridge wired into MainActivity');
