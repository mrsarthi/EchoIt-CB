/**
 * Re-applies release signing to the generated Android project.
 *
 * `src-tauri/gen/` is gitignored and rebuilt by `tauri android init`, so any
 * edit to `build.gradle.kts` is temporary by construction. This script is the
 * durable half: the generated project stays disposable, and this puts the
 * signing config back whenever it is regenerated.
 *
 *   npm run android:sign
 *
 * Idempotent — running it twice is a no-op. Run it after any `android init`,
 * and before any release build.
 *
 * The secrets themselves live in `src-tauri/keystore.properties`, which is
 * gitignored and referenced by path, never inlined here.
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const gradle = join(root, 'src-tauri/gen/android/app/build.gradle.kts');
const props = join(root, 'src-tauri/keystore.properties');

function fail(msg) {
  console.error(`android:sign — ${msg}`);
  process.exit(1);
}

if (!existsSync(props)) {
  fail(
    'src-tauri/keystore.properties is missing.\n' +
    '  Without it a release build is signed with the debug key, which Android\n' +
    '  treats as a different app: testers would have to uninstall, and\n' +
    '  uninstalling wipes their message history. Restore it from your backup.',
  );
}
if (!existsSync(gradle)) {
  fail('src-tauri/gen/android not found. Run `npx tauri android init` first.');
}

let src = readFileSync(gradle, 'utf8');

if (src.includes('signingConfigs')) {
  console.log('android:sign — already applied, nothing to do.');
  process.exit(0);
}

// `rootProject` is gen/android, so ../.. lands in src-tauri where the
// properties and the keystore live — outside the regenerated tree.
const signingBlock = `
    // Applied by scripts/apply-android-signing.mjs — do not hand-edit, this
    // file is regenerated by \`tauri android init\`. Re-run the script instead.
    signingConfigs {
        create("release") {
            val propsFile = rootProject.file("../../keystore.properties")
            val props = Properties().apply { propsFile.inputStream().use { load(it) } }
            keyAlias = props.getProperty("keyAlias")
            keyPassword = props.getProperty("keyPassword")
            // Resolved against the properties file's own directory so the
            // keystore path stays independent of Gradle's working directory.
            storeFile = propsFile.parentFile.resolve(props.getProperty("storeFile"))
            storePassword = props.getProperty("storePassword")
        }
    }
`;

// Insert the signingConfigs block just before buildTypes.
const buildTypesAt = src.indexOf('    buildTypes {');
if (buildTypesAt === -1) fail('could not find the buildTypes block in build.gradle.kts');
src = src.slice(0, buildTypesAt) + signingBlock + '\n' + src.slice(buildTypesAt);

// Point the release buildType at it. Matched by regex, not a literal: the
// generated file uses CRLF on Windows, and a '\n' literal silently fails to
// match — which presents as "could not find the release buildType".
const releaseMarker = /([ \t]*getByName\("release"\)\s*\{[ \t]*\r?\n)/;
if (!releaseMarker.test(src)) fail('could not find the release buildType');
src = src.replace(
  releaseMarker,
  '$1            signingConfig = signingConfigs.getByName("release")\n',
);

writeFileSync(gradle, src, 'utf8');
console.log('android:sign — signing config applied to gen/android/app/build.gradle.kts');
