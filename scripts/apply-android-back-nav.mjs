#!/usr/bin/env node
/**
 * Hand the Android back button to the web layer, and give the web layer a way
 * to actually close the app.
 *
 * ## Why this is native code rather than JavaScript
 *
 * Two earlier attempts used `history.pushState` and `popstate`. Neither could
 * have worked, and the device said so:
 *
 *  1. `TauriActivity` ships `handleBackNavigation = false`, which switches off
 *     wry's `OnBackPressedCallback` entirely. The back button finishes the
 *     activity without consulting the webview at all.
 *  2. Overriding that back to `true` still exited. wry's callback only calls
 *     `goBack()` when `WebView.canGoBack()` is true, and that reflects the
 *     native navigation list — not entries added by `history.pushState`.
 *     Measured: the app exited on the first back press with `history.length`
 *     of 4.
 *
 * So the press is intercepted here and forwarded to JavaScript as an event.
 * No dependence on webview history, and the app always gets to decide.
 *
 * `WryActivity.mWebView` is private, but `onWebViewCreate(webView)` is `open`
 * and receives the WebView — that is the hook.
 *
 * ## Why there is also an exit bridge
 *
 * Once back stops closing the app, something has to. `getCurrentWindow()
 * .close()` is a no-op on Android — measured: the exit prompt's Close button
 * left the process running, turning the prompt into a trap. `EchoItExit.exit()`
 * calls `finish()`, which is graceful enough that the webview still gets
 * `pagehide` and the last checkpoint lands.
 *
 * ## Durability
 *
 * `src-tauri/gen/` is gitignored and regenerated by `tauri android init`, so a
 * hand edit there is temporary by construction. This script is the durable
 * half, exactly like `apply-android-signing.mjs`.
 *
 *   npm run android:back-nav      (or npm run android:prepare for both)
 *
 * Idempotent — see BEGIN/END below for why that took two tries.
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const ACTIVITY = join(
  'src-tauri', 'gen', 'android', 'app', 'src', 'main', 'java',
  'io', 'github', 'mrsarthi', 'echoit', 'MainActivity.kt',
);

if (!existsSync(ACTIVITY)) {
  console.error(`No ${ACTIVITY}. Run \`npx tauri android init\` first.`);
  process.exit(1);
}

let source = readFileSync(ACTIVITY, 'utf8');

/*
 * Everything this script inserts lives between these markers.
 *
 * The first version guarded on "the file already mentions echoit:back" and
 * returned early. When the inserted body later grew the exit bridge, that
 * guard still matched an older region, and the result was a *second*
 * `onWebViewCreate` override in the same class — a file that would not
 * compile. Removing our own region before rewriting it is the only form of
 * idempotence that survives the body changing.
 */
const BEGIN = '  // >>> echoit back-nav (generated by scripts/apply-android-back-nav.mjs)';
const END = '  // <<< echoit back-nav';

/** Cut everything between two literal markers, inclusive. Plain string work — no regex escaping. */
function stripRegion(text, begin, end) {
  for (;;) {
    const from = text.indexOf(begin);
    if (from === -1) return text;
    const to = text.indexOf(end, from);
    if (to === -1) {
      console.error(`Found "${begin.trim()}" with no matching end. Refusing to guess.`);
      process.exit(1);
    }
    text = text.slice(0, from) + text.slice(to + end.length).replace(/^\n/, '');
  }
}

source = stripRegion(source, `${BEGIN}\n`, `${END}\n`);

// Versions predating the sentinels: the bare override, and an earlier
// handleBackNavigation attempt that did not work (see the note above).
source = stripRegion(source, '  /**\n   * Forward the back press to the web layer.', '\n  }\n');
source = source.replace(
  /\n\s*\/\/ Hand the back button to the web layer\.[\s\S]*?override val handleBackNavigation: Boolean = true\n/,
  '\n',
);

const CLASS_HEADER = /(class\s+MainActivity\s*:\s*TauriActivity\s*\(\s*\)\s*\{\s*\r?\n)/;
if (!CLASS_HEADER.test(source)) {
  console.error(`Could not find the MainActivity class header in ${ACTIVITY}.`);
  console.error('Tauri may have changed what it generates. Refusing to guess.');
  process.exit(1);
}

const BODY = `${BEGIN}
  /**
   * Forward the back press to the web layer.
   *
   * Registered here rather than relying on wry's own handling, which is
   * switched off by TauriActivity and, even when enabled, only reacts to
   * WebView.canGoBack() — that tracks native navigations, not history
   * entries added by pushState. Measured on a device: the app exited on the
   * first back press with four history entries available.
   *
   * The web layer listens for "echoit:back" and decides: step back through
   * its own navigation, or ask before closing. If it ever stops listening the
   * button does nothing, which is a worse failure than exiting — so AppShell
   * installs its listener at mount, before any view can be opened.
   */
  override fun onWebViewCreate(webView: android.webkit.WebView) {
    super.onWebViewCreate(webView)

    onBackPressedDispatcher.addCallback(
      this,
      object : androidx.activity.OnBackPressedCallback(true) {
        override fun handleOnBackPressed() {
          webView.evaluateJavascript(
            "window.dispatchEvent(new CustomEvent('echoit:back'))",
            null,
          )
        }
      },
    )

    /*
     * Let the web layer close the app.
     *
     * getCurrentWindow().close() is a no-op on Android -- measured: the exit
     * prompt's Close button left the process running. Without this the prompt
     * is a trap, which is worse than the exiting it replaced.
     *
     * finish() rather than killing the process, so the webview still gets
     * pagehide and the last checkpoint lands.
     */
    webView.addJavascriptInterface(
      object {
        @android.webkit.JavascriptInterface
        fun exit() {
          runOnUiThread { finish() }
        }
      },
      "EchoItExit",
    )
  }
${END}
`;

const patched = source.replace(CLASS_HEADER, `$1${BODY}`);
if (patched === source) {
  console.error('android:back-nav — replacement made no change. Not writing.');
  process.exit(1);
}

writeFileSync(ACTIVITY, patched, 'utf8');
console.log('android:back-nav — back press forwarded as "echoit:back"; EchoItExit.exit() closes the app');
